function m1a_require_float_init(model)
% Read-only InitFcn guard. Never initializes or rewrites model/base variables.
message='Execute init_PMLSM_PI_FOC_Float_Baseline in Base Workspace before Run.';
assert(evalin('base','exist(''PMLSM_M1A_InitVersion'',''var'')==1') && ...
    isequal(evalin('base','PMLSM_M1A_InitVersion'),20261023), ...
    'M1A:INITIALIZATION_REQUIRED',message);
names={'Kp_ACR','Ki_ACR','Kp_ASR','Ki_ASR','Kaw_d','Kaw_q','Kaw_s', ...
    'Kp_pos','Udc','PMLSM_Rs_ohm','PMLSM_Ld_H','PMLSM_Lq_H', ...
    'PMLSM_psi_f_Wb','PMLSM_M_kg','PMLSM_Kf_peak_N_per_Apeak', ...
    'PMLSM_tau_NN_m','Ts','T_pwm','Ts_ACR','Ts_ASR','Ts_POS','Ts_Plant', ...
    'PMLSM_Ts_s','M1A_PWM_Update_Delay_s','PMLSM_deadtime_s','PMLSM_deadtime_ratio'};
v=struct;
for k=1:numel(names)
    assert(evalin('base',sprintf('exist(''%s'',''var'')==1',names{k})), ...
        'M1A:PARAMETER_REQUIRED','%s Missing %s.',message,names{k});
    value=evalin('base',names{k});
    assert(isnumeric(value)&&isscalar(value)&&isreal(value)&&isfinite(value), ...
        'M1A:PARAMETER_VALUE','%s Invalid %s.',message,names{k});
    v.(names{k})=value;
end
assert(v.Ts==v.Ts_ACR && v.T_pwm==v.Ts_ACR && ...
    abs(v.Ts_ASR/v.Ts_ACR-10)<1e-12 && abs(v.Ts_POS/v.Ts_ASR-10)<1e-12 && ...
    v.PMLSM_Ts_s==v.Ts_Plant && v.M1A_PWM_Update_Delay_s==v.T_pwm/2 && ...
    abs(v.PMLSM_deadtime_ratio-v.PMLSM_deadtime_s/v.T_pwm)<1e-12, ...
    'M1A:TIMEBASE','%s Inconsistent timebase/deadtime.',message);
assert(v.Ts_Plant>0 && abs(v.Ts_ACR/v.Ts_Plant-round(v.Ts_ACR/v.Ts_Plant))<1e-9);
workspace=get_param(model,'ModelWorkspace');
assert(isempty(whos(workspace)),'M1A:WORKSPACE_SHADOW','Model Workspace must be empty.');
end
